#[test]
fn le_vecteur_282_de_la_norme_se_scelle_au_bit_pres() {
    let scelle = sceller(&CLE_282, &NONCE_282, AAD_282, CLAIR_282);
    let (chiffre, sceau) = scelle.split_at(CLAIR_282.len());
    assert_eq!(chiffre, CHIFFRE_282);
    assert_eq!(sceau, SCEAU_282);
    assert_eq!(
        ouvrir(&CLE_282, &NONCE_282, AAD_282, &scelle).as_deref(),
        Some(CLAIR_282)
    );
}

/// Annexe A.5 : 265 octets — plusieurs blocs de ChaCha20, un dernier bloc incomplet de Poly1305.
#[test]
fn le_vecteur_a5_de_la_norme_s_ouvre() {
    let mut scelle = CHIFFRE_A5.to_vec();
    scelle.extend_from_slice(SCEAU_A5);
    assert_eq!(
        ouvrir(&CLE_A5, &NONCE_A5, AAD_A5, &scelle).as_deref(),
        Some(CLAIR_A5)
    );
    assert_eq!(sceller(&CLE_A5, &NONCE_A5, AAD_A5, CLAIR_A5), scelle);
}

/// **Rien ne s'ouvre qui a été touché** : un bit du chiffré, du sceau, des données associées, la
/// clé, le nonce ; ni un message tronqué.
#[test]
fn un_seul_bit_change_et_rien_ne_s_ouvre() {
    let scelle = sceller(&CLE_282, &NONCE_282, AAD_282, CLAIR_282);
    for i in [
        0,
        57,
        CLAIR_282.len() - 1,
        CLAIR_282.len(),
        scelle.len() - 1,
    ] {
        let mut abime = scelle.clone();
        abime[i] ^= 1;
        assert_eq!(
            ouvrir(&CLE_282, &NONCE_282, AAD_282, &abime),
            None,
            "octet {i}"
        );
    }
    let mut aad = AAD_282.to_vec();
    aad[0] ^= 0x80;
    assert_eq!(ouvrir(&CLE_282, &NONCE_282, &aad, &scelle), None);
    let mut cle = CLE_282;
    cle[31] ^= 1;
    assert_eq!(ouvrir(&cle, &NONCE_282, AAD_282, &scelle), None);
    let mut nonce = NONCE_282;
    nonce[0] ^= 1;
    assert_eq!(ouvrir(&CLE_282, &nonce, AAD_282, &scelle), None);
    assert_eq!(ouvrir(&CLE_282, &NONCE_282, AAD_282, &scelle[..15]), None);
}

/// Toute longueur, autour des frontières des blocs (16 pour le sceau, 64 pour le flux) : sceller
/// puis ouvrir rend l'original.
#[test]
fn toute_longueur_se_scelle_et_s_ouvre() {
    for n in (0..=130).chain([255, 256, 257, 1000]) {
        let clair: Vec<u8> = (0..n).map(|i| (i * 31 + 7) as u8).collect();
        let scelle = sceller(&CLE_A5, &NONCE_A5, b"geste 42", &clair);
        assert_eq!(scelle.len(), n + 16);
        assert_eq!(
            ouvrir(&CLE_A5, &NONCE_A5, b"geste 42", &scelle),
            Some(clair),
            "{n}"
        );
    }
}

/// Annexe A.3, vecteurs 5 à 11 : les cas limites de la réduction de Poly1305 — un résultat
/// partiellement réduit, `s` qui déborde, des membres pleins de uns.
const POLY1305_LIMITES: [(&str, &str, &str, &str); 7] = [
    ("02000000000000000000000000000000", "00000000000000000000000000000000", "ffffffffffffffffffffffffffffffff", "03000000000000000000000000000000"),
    ("02000000000000000000000000000000", "ffffffffffffffffffffffffffffffff", "02000000000000000000000000000000", "03000000000000000000000000000000"),
    ("01000000000000000000000000000000", "00000000000000000000000000000000", "fffffffffffffffffffffffffffffffff0ffffffffffffffffffffffffffffff11000000000000000000000000000000", "05000000000000000000000000000000"),
    ("01000000000000000000000000000000", "00000000000000000000000000000000", "fffffffffffffffffffffffffffffffffbfefefefefefefefefefefefefefefe01010101010101010101010101010101", "00000000000000000000000000000000"),
    ("02000000000000000000000000000000", "00000000000000000000000000000000", "fdffffffffffffffffffffffffffffff", "faffffffffffffffffffffffffffffff"),
    ("01000000000000000400000000000000", "00000000000000000000000000000000", "e33594d7505e43b900000000000000003394d7505e4379cd01000000000000000000000000000000000000000000000001000000000000000000000000000000", "14000000000000005500000000000000"),
    ("01000000000000000400000000000000", "00000000000000000000000000000000", "e33594d7505e43b900000000000000003394d7505e4379cd010000000000000000000000000000000000000000000000", "13000000000000000000000000000000"),
];

fn octets(hex: &str) -> Vec<u8> {
    (0..hex.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&hex[i..i + 2], 16).expect("hexadécimal"))
        .collect()
}

/// **Les cas limites de Poly1305** (A.3, 5 à 11) : c'est là que se trompent les implémentations
/// faites à la main — la réduction finale, le report de `s`, les membres pleins.
#[test]
fn poly1305_tient_les_cas_limites_de_la_norme() {
    for (r, s, donnees, sceau) in POLY1305_LIMITES {
        let mut cle = [0u8; 32];
        cle[..16].copy_from_slice(&octets(r));
        cle[16..].copy_from_slice(&octets(s));
        assert_eq!(
            super::poly1305(&cle, &octets(donnees)).to_vec(),
            octets(sceau),
            "{donnees}"
        );
    }
}
